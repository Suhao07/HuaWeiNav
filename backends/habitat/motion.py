"""Habitat primitive execution through the shared motion owner."""
from uuid import uuid4

from motion.supervisor import MotionSupervisor
from motion.contracts import MotionGoal, MotionGoalMode, NavigationIntent, NavigationStatus, NavigationStatusCode


class HabitatMotionController:
    """Execute discrete simulator actions and retain their observations.

    Args:
        env: Existing Habitat environment; detection and planning stay outside.

    REACHED 在此表示一次离散动作执行完成。目标到达和任务成功由原导航逻辑、
    验证器与独立 evaluator 分别判断。
    """
    def __init__(self, env, agent=None):
        self.env = env
        self.agent = agent
        self.waypoint_goal = None
        self.waypoint_goal_id = None
        self.observations = {}
        self.statuses = {}

    def send_goal(self, goal: MotionGoal) -> str:
        """Execute one backend primitive and return its completed request ID."""
        goal_id = str(uuid4())
        if goal.action is None:
            if self.agent is None or goal.goal_pose is None:
                raise ValueError("Habitat waypoint execution requires an agent and pose")
            if goal.goal_pose.frame_id != "mapper_local":
                raise ValueError("Habitat waypoints require mapper_local coordinates")
            self.waypoint_goal, self.waypoint_goal_id = goal, goal_id
            self.statuses[goal_id] = NavigationStatus(NavigationStatusCode.QUEUED, goal_id=goal_id)
            return goal_id
        self.observations[goal_id] = self.env.step(goal.action)
        self.statuses[goal_id] = NavigationStatus(
            NavigationStatusCode.REACHED, goal_id=goal_id,
            metadata={"completion_scope": "primitive", "action": goal.action},
        )
        return goal_id

    def poll_status(self, goal_id: str) -> NavigationStatus:
        """Return the execution receipt; querying never advances simulation."""
        return self.statuses[goal_id]

    def cancel(self, goal_id=None) -> None:
        """Cancel the outstanding waypoint before the next simulator tick."""
        if self.waypoint_goal_id is not None and goal_id in (None, self.waypoint_goal_id):
            self.statuses[self.waypoint_goal_id] = NavigationStatus(
                NavigationStatusCode.PREEMPTED, goal_id=self.waypoint_goal_id,
            )
            self.waypoint_goal = self.waypoint_goal_id = None

    def hold(self) -> None:
        """Stop the active waypoint pump; resumption requires a new proposal."""
        self.cancel()

    def advance(self):
        """Advance one primitive of an admitted waypoint using the existing planner.

        模型推理和状态查询均不推进仿真；episode driver 驱动此方法。
        局部规划器返回 STOP 表示该 waypoint 到达，任务 STOP 由完成工具触发。
        """
        import numpy as np
        from navigation.action_controller import next_action_to_waypoint

        if self.waypoint_goal is None:
            return
        goal_id = self.waypoint_goal_id
        if self.env.episode_over:
            status = NavigationStatusCode.TIMEOUT
        else:
            waypoint = np.asarray(self.waypoint_goal.goal_pose.position, dtype=float)
            action = next_action_to_waypoint(self.agent, waypoint)
            if action is None:
                status = NavigationStatusCode.BLOCKED
            elif int(action) == 0:
                status = NavigationStatusCode.REACHED
            else:
                self.agent.obs = self.env.step(int(action))
                self.agent.update_trajectory()
                status = NavigationStatusCode.RUNNING
        self.statuses[goal_id] = NavigationStatus(
            status, goal_id=goal_id, stamp=float(self.agent.episode_steps),
            metadata={"completion_scope": "waypoint"},
        )
        if self.statuses[goal_id].is_terminal():
            self.waypoint_goal = self.waypoint_goal_id = None


class HabitatExecution:
    """Bind an episode's primitive actions to one MotionSupervisor."""
    def __init__(self, env):
        self.controller = HabitatMotionController(env)
        self.motion = MotionSupervisor(self.controller)

    def step(self, action: int, *, request_id=None):
        """Execute the existing planner's action once and return its observation.

        Args:
            action: Habitat discrete action, including episode STOP (0).
            request_id: Optional stable id for an idempotent retry.

        Returns:
            The observation generated by this exact simulator step.
        """
        action = int(action)
        mode = MotionGoalMode.STOP if action == 0 else MotionGoalMode.EXPLORE
        goal = MotionGoal(mode=mode, action=action)
        goal_id = self.motion.submit(NavigationIntent(mode=mode), goal, request_id=request_id)
        self.motion.poll_active()
        if request_id is None:
            return self.controller.observations.pop(goal_id)
        return self.controller.observations[goal_id]
